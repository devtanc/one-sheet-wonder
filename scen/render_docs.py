def typo(s): return s.replace("'", "\u2019")
def sgn(v): return f"+{v}" if v > 0 else ("\u2212" + str(-v) if v < 0 else "0")
def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return out + [""]

def engine_constants():
    """Ability numbers straight from engine2.py (module-level NAME = value lines)."""
    src = open(os.path.join(ROOT, "engine2.py")).read(); out = {}
    for name in ("FURY_HP", "BLOOD_HP", "OATH_DIV", "OATH_CAP", "AURA_DIV", "AURA_CAP", "CLAWS_EXPOSE", "CLAWS_STEPS", "TRAMPLE_LANCE"):
        m = re.search(rf"P\.get\('{name}',\s*([0-9.]+)\)", src)   # the engine's defaults: P.get('NAME', value)
        if m: out[name] = m.group(1)
    missing = [n for n in ("FURY_HP", "BLOOD_HP", "OATH_DIV", "OATH_CAP", "AURA_DIV", "AURA_CAP", "CLAWS_EXPOSE", "CLAWS_STEPS") if n not in out]
    assert not missing, f"engine constants not found: {missing}"
    return out

