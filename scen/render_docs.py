def build():
    rules = RR.MarkdownFlow(); RR.content(rules)
    return {"docs/rules.md": rules.text(), "docs/hero-warrior.md": hero_doc(), "docs/content-reference.md": content_doc()}

if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit non-zero if any generated doc is out of date")
    a = ap.parse_args(); stale = []
    for path, text in build().items():
        full = os.path.join(ROOT, path)
        if a.check:
            if not os.path.exists(full) or open(full).read() != text: stale.append(path)
        else:
            os.makedirs(os.path.dirname(full), exist_ok=True); open(full, "w").write(text); print("wrote", path)
    if a.check:
        print("docs up to date" if not stale else "out of date: " + ", ".join(stale) + " (run python3 scen/render_docs.py)")
        sys.exit(1 if stale else 0)
