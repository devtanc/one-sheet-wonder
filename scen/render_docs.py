# --- scenario content ----------------------------------------------------------------------------------------
def attacks(atks):
    out = []
    for a in atks:
        d, heavy = a[0], a[1]; tag = a[2] if len(a) > 2 else ""
        if d == 0: out.append("wind-up"); continue
        s = f"{d}{'H' if heavy else ''}"
        if tag: s = f"{P.ATTACK_TAG_KEYWORD[tag]} {s}"
        out.append(s)
    return ", ".join(out)

